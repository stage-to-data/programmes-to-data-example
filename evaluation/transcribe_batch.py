"""Submit a corpus of programme page images to Claude's batch API for transcription.

This is the transcription half of the prompt evaluation reported in the STAGE
article: it produces the `results/<campaign>/<pass>/` folders that `evaluation.ipynb`
then scores against the ground truth. The demo pipeline in
`Hamlet_example/full-pipeline.ipynb` transcribes page by page via Ollama, which
is fine for a single programme; evaluating a prompt over 151 pages is an order
of magnitude cheaper and faster through the batch API.

Layout produced, per run:

    results/<campaign>/<pass>/
        requests/         one .json per submitted batch, plus _id_to_file.json
        raw-responses/    one .json per returned page
        transcriptions/   one .md per page  <-- what evaluation.ipynb consumes

Usage:

    export ANTHROPIC_API_KEY=...
    python transcribe_batch.py --images <folder of .jpg> --pass-name prompt-5

The prompt is read by default from `prompts/round-3/<pass-name>.txt`.
"""

import argparse
import os
import sys
import time
import unicodedata
from pathlib import Path

import llmwrap

# Run straight from a checkout, without having to pip install the package first.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ptod.utils import collect_files, read_txt, write_json, write_txt  # noqa: E402

SYSTEM_PROMPT = "You are a tool for the transcription of textual data from scanned images."
DEFAULT_MODEL = "claude-3-7-sonnet-20250219"
MAX_TOKENS = 3000
BATCH_SIZE = 50          # Anthropic accepts more; 50 keeps each batch inspectable.
POLL_INTERVAL_S = 60


def chunked(items, size):
    for start in range(0, len(items), size):
        yield items[start:start + size]


def make_wrapper(model_id, api_key):
    return llmwrap.BatchClaudeWrapper(
        model=model_id,
        api_key=api_key,
        system_prompt=SYSTEM_PROMPT,
        max_tokens=MAX_TOKENS,
    )


def submit(image_paths, prompt_text, requests_dir, model_id, api_key):
    """Submit the images in batches.

    Returns:
        ``(batches, id_to_file)`` where ``batches`` is a list of
        ``(wrapper, request_json_path)`` — the path is what ``poll`` and
        ``retrieve_tasks`` need — and ``id_to_file`` maps the request ids
        generated by llmwrap back to the source image, so that results can be
        written under the original page names.
    """
    requests_dir.mkdir(parents=True, exist_ok=True)
    batches = []
    id_to_file = {}

    for i, chunk in enumerate(chunked(image_paths, BATCH_SIZE), start=1):
        prompts = [llmwrap.Prompt(prompt_text, images=[path]) for path in chunk]

        wrapper = make_wrapper(model_id, api_key)
        response = wrapper.submit_tasks(prompts)
        request_path = response.write(str(requests_dir))

        # llmwrap assigns the ids inside submit_tasks, so recover the mapping
        # from the response rather than trying to pre-assign it.
        for item in response.prompts:
            images = getattr(item["prompt"], "images", [])
            if images:
                id_to_file[item["id"]] = images[0]

        batches.append((wrapper, request_path))
        print(f"  submitted batch {i} ({len(chunk)} pages) -> "
              f"{os.path.basename(request_path)}")

    write_json(str(requests_dir / "_id_to_file.json"), id_to_file)
    return batches, id_to_file


def wait_and_retrieve(batches, results_dir):
    """Poll until every batch has ended, writing out each page result."""
    results_dir.mkdir(parents=True, exist_ok=True)
    pending = list(batches)
    retrieved = {}

    while pending:
        still_pending = []

        for wrapper, request_path in pending:
            state = wrapper.poll(request_path)
            if state.get("processing_status") == "ended":
                for key, item in wrapper.retrieve_tasks(request_path).items():
                    item.write(str(results_dir))
                    retrieved[key] = item
                counts = state.get("request_counts", {})
                print(f"  {os.path.basename(request_path)} ended: {counts}")
            else:
                still_pending.append((wrapper, request_path))

        pending = still_pending
        if pending:
            print(f"  {len(pending)} batch(es) still running, "
                  f"waiting {POLL_INTERVAL_S}s...")
            time.sleep(POLL_INTERVAL_S)

    return retrieved


def write_markdown(retrieved, id_to_file, out_dir):
    """One .md per page, named after the source image."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = 0
    failed = []

    for key, item in retrieved.items():
        source = id_to_file.get(key)
        if source is None:
            failed.append({"id": key, "error": "no source file recorded"})
            continue

        # A dict payload means llmwrap caught an API-level error for this page.
        if isinstance(item.content, dict):
            failed.append({"id": key, "file": source, "error": item.content})
            continue

        # NFC-normalise: accented page names must be written in one consistent
        # Unicode form, otherwise they will not pair with the ground truth,
        # whose file names are normalised the same way in evaluation.ipynb.
        stem = unicodedata.normalize(
            "NFC", os.path.splitext(os.path.basename(source))[0])
        write_txt(str(out_dir / f"{stem}.md"), item.content)
        written += 1

    if failed:
        write_json(str(out_dir / "_failed_files.json"), {"fails": failed})

    return written, failed


def main():
    parser = argparse.ArgumentParser(
        description="Batch-transcribe programme pages with Claude.")
    parser.add_argument("--images", required=True,
                        help="folder of preprocessed page images (.jpg)")
    parser.add_argument("--pass-name", required=True,
                        help="test pass name, e.g. prompt-4")
    parser.add_argument("--prompt-file", default=None,
                        help="prompt text file "
                             "(default: prompts/round-3/<pass-name>.txt)")
    parser.add_argument("--prompt-round", default="round-3",
                        help="subfolder of prompts/ holding the prompt")
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--campaign", default="new-tests",
                        help="groups runs under results/<campaign>/")
    args = parser.parse_args()

    api_key = os.environ.get("ANTHROPIC_API_KEY")
    if not api_key:
        raise SystemExit("Set ANTHROPIC_API_KEY in the environment.")

    prompt_file = (Path(args.prompt_file) if args.prompt_file
                   else Path("prompts") / args.prompt_round / f"{args.pass_name}.txt")
    prompt_text = read_txt(str(prompt_file))
    if prompt_text is None:
        raise SystemExit(f"Prompt file not found: {prompt_file}")

    image_paths = sorted(collect_files(args.images, ["jpg", "jpeg"]))
    if not image_paths:
        raise SystemExit(f"No images found in {args.images}")

    print(f"\N{LEFT-POINTING MAGNIFYING GLASS} {len(image_paths)} pages, "
          f"model {args.model}, prompt {prompt_file.name}")

    pass_dir = Path("results") / args.campaign / args.pass_name

    print("Submitting...")
    batches, id_to_file = submit(image_paths, prompt_text,
                                 pass_dir / "requests", args.model, api_key)

    print("Waiting for results...")
    retrieved = wait_and_retrieve(batches, pass_dir / "raw-responses")

    written, failed = write_markdown(retrieved, id_to_file,
                                    pass_dir / "transcriptions")
    print(f"\N{THUMBS UP SIGN} {written}/{len(image_paths)} pages written to "
          f"{pass_dir / 'transcriptions'}")

    if failed:
        print(f"\N{WARNING SIGN} {len(failed)} page(s) failed, see "
              f"{pass_dir / 'transcriptions' / '_failed_files.json'}")


if __name__ == "__main__":
    main()
